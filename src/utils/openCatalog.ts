/**
 * Parses an OPDS Atom XML feed string into structured book entries
 */
export function parseOpdsFeedXml(xmlString: string): Array<{
  id: string;
  title: string;
  author: string;
  summary: string;
  downloadUrl?: string;
}> {
  if (typeof DOMParser !== 'undefined') {
    try {
      const parser = new DOMParser();
      const xmlDoc = parser.parseFromString(xmlString, 'text/xml');
      const entries = xmlDoc.querySelectorAll('entry');
      if (entries.length > 0) {
        const results: Array<{ id: string; title: string; author: string; summary: string; downloadUrl?: string }> = [];

        entries.forEach((entry, idx) => {
          const title = entry.querySelector('title')?.textContent?.trim() || `Book #${idx + 1}`;
          const author = entry.querySelector('author name, author')?.textContent?.trim() || 'Unknown Author';
          const summary = entry.querySelector('summary, content')?.textContent?.trim() || '';
          const link = entry.querySelector('link[type*="epub"], link[type*="text/plain"], link[rel*="acquisition"]')?.getAttribute('href') || undefined;
          const id = entry.querySelector('id')?.textContent?.trim() || `opds_${idx}_${Date.now()}`;

          results.push({
            id,
            title,
            author,
            summary: summary.slice(0, 300),
            downloadUrl: link,
          });
        });

        return results;
      }
    } catch (err) {
      console.error('DOMParser failed in parseOpdsFeedXml:', err);
    }
  }

  // Regex fallback for non-DOM / Node / test environments
  const entryMatches = xmlString.match(/<entry[\s\S]*?<\/entry>/gi) || [];
  return entryMatches.map((entryXml, idx) => {
    const title = entryXml.match(/<title[^>]*>([\s\S]*?)<\/title>/i)?.[1]?.trim() || `Book #${idx + 1}`;
    const author = entryXml.match(/<author[^>]*>[\s\S]*?<name[^>]*>([\s\S]*?)<\/name>/i)?.[1]?.trim() ||
                   entryXml.match(/<author[^>]*>([\s\S]*?)<\/author>/i)?.[1]?.trim() || 'Unknown Author';
    const summary = entryXml.match(/<(summary|content)[^>]*>([\s\S]*?)<\/\1>/i)?.[2]?.trim() || '';
    const linkMatch = entryXml.match(/<link[^>]*href=["']([^"']+)["'][^>]*>/i);
    const downloadUrl = linkMatch ? linkMatch[1] : undefined;
    const id = entryXml.match(/<id[^>]*>([\s\S]*?)<\/id>/i)?.[1]?.trim() || `opds_${idx}_${Date.now()}`;

    return {
      id,
      title,
      author,
      summary: summary.slice(0, 300),
      downloadUrl,
    };
  });
}
